#!/usr/bin/env python3
# [Doruk-Aksoy] Writes features/acsvec/computation/acsvec_golden.inc: fua_Vec calls and their exact results, worked out apart from the C++.
"""Usage: python tools/gen_acsvec_golden.py > src/zandronum/src/features/acsvec/computation/acsvec_golden.inc

Every result is the true value rounded half away from zero to 1/65536 and saturated to
+-0x7FFFFFFF. The C++ searches for each rounded value; this derives it in closed form from
integer square roots of exact quotients, so the two can disagree only if one is wrong.
"""
import math
import random

MAX = 0x7FFFFFFF
MIN = -0x80000000
CHANNEL = 5
OPS = {"length2": 1, "length3": 2, "unit2": 3, "unit3": 4, "dot2": 5, "dot3": 6, "cross3": 7}


def sat(v):
    return max(-MAX, min(MAX, v))


def round_half_away(num, den):
    """num / den rounded half away from zero, den > 0."""
    sign = -1 if num < 0 else 1
    return sign * ((2 * abs(num) + den) // (2 * den))


def length(v):
    s = sum(c * c for c in v)
    # floor(sqrt(s) + 1/2) == floor((floor(2 sqrt(s)) + 1) / 2) and floor(2 sqrt(s)) == isqrt(4 s).
    return min(MAX, (math.isqrt(4 * s) + 1) // 2)


def unit(v):
    s = sum(c * c for c in v)
    out = []
    for c in v:
        if s == 0:
            out.append(0)
            continue
        q = abs(c) << 16
        n = (math.isqrt((4 * q * q) // s) + 1) // 2
        out.append(-n if c < 0 else n)
    return out


def dot(a, b):
    return sat(round_half_away(sum(x * y for x, y in zip(a, b)), 65536))


def cross(a, b):
    ax, ay, az = a
    bx, by, bz = b
    return [sat(round_half_away(n, 65536)) for n in (ay * bz - az * by, az * bx - ax * bz, ax * by - ay * bx)]


def component(rng):
    kind = rng.random()
    if kind < 0.08:
        return rng.choice([0, 1, -1, MAX, MIN, 65536, -65536, 32768, -32768])
    bits = rng.choice([4, 8, 12, 16, 18, 20, 22, 24, 26, 28, 30, 31])
    return rng.randint(-(1 << bits) + (1 if bits == 31 else 0), (1 << bits) - 1)


def case(op, operands, results):
    args = list(operands) + [CHANNEL, OPS[op]]
    return "\t{ %d, { %s }, %d, { %s } }," % (
        len(args), ", ".join(c_int(a) for a in args), len(results), ", ".join(c_int(r) for r in results))


def c_int(v):
    return "(-2147483647 - 1)" if v == MIN else str(v)


def main():
    rng = random.Random(20261116)
    lines = []
    # [Doruk-Aksoy] Halfway dot products (x * 32768 / 65536 is x halves), the smallest unit vector and the extremes.
    lines.append(case("dot2", (1, 0, 32768, 0), [dot((1, 0), (32768, 0))]))
    lines.append(case("dot2", (-1, 0, 32768, 0), [dot((-1, 0), (32768, 0))]))
    lines.append(case("dot2", (3, 0, 32768, 0), [dot((3, 0), (32768, 0))]))
    lines.append(case("dot2", (-3, 0, 32768, 0), [dot((-3, 0), (32768, 0))]))
    lines.append(case("unit2", (1, 0), unit((1, 0))))
    lines.append(case("length3", (MIN, MIN, MIN), [length((MIN, MIN, MIN))]))
    lines.append(case("unit3", (MIN, MIN, MIN), unit((MIN, MIN, MIN))))
    lines.append(case("unit3", (0, 0, 0), unit((0, 0, 0))))
    lines.append(case("dot3", (MIN, MIN, MIN, MIN, MIN, MIN), [dot((MIN,) * 3, (MIN,) * 3)]))
    lines.append(case("dot3", (MIN, MIN, MIN, MAX, MAX, MAX), [dot((MIN,) * 3, (MAX,) * 3)]))
    lines.append(case("cross3", (MIN, MAX, MIN, MAX, MIN, MAX), cross((MIN, MAX, MIN), (MAX, MIN, MAX))))
    for _ in range(120):
        for n in (2, 3):
            v = [component(rng) for _ in range(n)]
            w = [component(rng) for _ in range(n)]
            lines.append(case("length%d" % n, v, [length(v)]))
            lines.append(case("unit%d" % n, v, unit(v)))
            lines.append(case("dot%d" % n, v + w, [dot(v, w)]))
        a = [component(rng) for _ in range(3)]
        b = [component(rng) for _ in range(3)]
        lines.append(case("cross3", a + b, cross(a, b)))
    print("// [Doruk-Aksoy] Generated by tools/gen_acsvec_golden.py; argument count, arguments (operands, channel, op), result count, results.")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
